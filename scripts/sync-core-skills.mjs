#!/usr/bin/env node
// Bundles skills/*/SKILL.md into src/worker/core-skills.ts, which the MCP server answers as prompts (docs/MCP.md, "Skills").
// Run it after editing a skill: `npm run sync:skills`. With --check it writes nothing and exits 1 when core-skills.ts is
// stale; test/core-skills.test.ts runs that, so a skill edit without a sync fails the tests. Only SKILL.md is bundled:
// the reference files beside it stay in the repository for agents that read the folder.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'skills');
const OUT = path.join(ROOT, 'src/worker/core-skills.ts');

/** A frontmatter value: plain, quoted, or folded over several indented lines (`>` or `|`). */
function field(front, key) {
  const lines = front.split('\n');
  const i = lines.findIndex((l) => l.startsWith(`${key}:`));
  if (i < 0) return undefined;
  let v = lines[i].slice(key.length + 1).trim();
  if (/^[>|][+-]?$/.test(v)) {
    const more = [];
    for (let j = i + 1; j < lines.length && /^\s+\S/.test(lines[j]); j++) more.push(lines[j].trim());
    v = more.join(' ');
  }
  if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1);
  return v.trim() || undefined;
}

function parse(name) {
  const file = `skills/${name}/SKILL.md`;
  const text = fs.readFileSync(path.join(DIR, name, 'SKILL.md'), 'utf8').replace(/\r\n/g, '\n');
  const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text);
  if (!m) throw new Error(`${file} has no frontmatter`);
  if (field(m[1], 'name') !== name) throw new Error(`${file}: name must be ${name}`);
  const description = field(m[1], 'description');
  if (!description) throw new Error(`${file} has no description`);
  const body = m[2].trim();
  const title = /^# (.+)$/m.exec(body)?.[1].trim();
  if (!title) throw new Error(`${file} has no # heading`);
  return { name, title, description, body };
}

export function build() {
  const skills = fs.existsSync(DIR)
    ? fs
        .readdirSync(DIR, { withFileTypes: true })
        .filter((d) => d.isDirectory() && fs.existsSync(path.join(DIR, d.name, 'SKILL.md')))
        .map((d) => d.name)
        .sort()
        .map(parse)
    : [];
  const source =
    '// Generated by scripts/sync-core-skills.mjs from skills/*/SKILL.md. Edit the SKILL.md files, then run `npm run sync:skills`.\n' +
    "// The MCP server answers these as prompts in every edition (src/worker/mcp.ts); FounderData Pro's skills join them.\n" +
    'export interface CoreSkill {\n  name: string;\n  title: string;\n  description: string;\n  body: string;\n}\n\n' +
    `export const CORE_SKILLS: CoreSkill[] = ${JSON.stringify(skills, null, 2)};\n`;
  return { skills, source };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { skills, source } = build();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== source) {
      console.error('src/worker/core-skills.ts is stale. Run: npm run sync:skills');
      process.exit(1);
    }
    console.log(`core-skills.ts is current: ${skills.length} skills`);
  } else {
    fs.writeFileSync(OUT, source);
    console.log(`Wrote src/worker/core-skills.ts: ${skills.map((s) => s.name).join(', ') || 'no skills'}`);
  }
}
